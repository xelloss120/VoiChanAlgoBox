// 遅延の実測
//
// 表示している遅延は、作り方から計算した値（理論値）。実際には、方式によって声の高さや周波数で遅れが変わる
// （TD-PSOLA は声の高さ、チャンネルボコーダや帯域ごとの周波数シフトは低い音ほど遅れる、など）。
// そこで、今の設定のまま、声に近いテスト音を、本体とは別に用意した処理（Engine）に通し、
// 入力と出力の音量の変化（包絡）がどれだけずれているかを、相互相関で求める。
// 波形ではなく包絡で比べるのは、WORLD のように波形を作り直す方式でも測れるようにするため。
//
// テスト音: 130Hz の母音（パルス列を3つの共振に直列に通したもの）を、音節のように 150ms 鳴らしては 100ms 休む。
// 間に息（高い雑音）を挟む。音量は、ゲートの初期のしきい値より十分大きい。
#pragma once

#include "Params.h"

namespace vcab
{

// 今の設定での処理全体の遅延（ms）を測る。重いので、音の処理のスレッドでは呼ばない。
// 測れなかったとき（出力がほぼ無音など）は負の値を返す
double measureLatencyMs (const ParamValues& params, double sampleRate);

} // namespace vcab
